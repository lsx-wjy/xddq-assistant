import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = path.dirname(fileURLToPath(import.meta.url));
const projectRoot = path.resolve(scriptDir, "..");
const protocolOutput = path.join(projectRoot, "src/game/net/Protocol.js");
const grpcRoot = path.join(projectRoot, "src/game/config/grpc");
const protobufOutput = path.join(grpcRoot, "protobuf");
const jsonOutput = path.join(grpcRoot, "json");

function parseArgs(argv) {
    const args = {};
    for (let index = 0; index < argv.length; index += 1) {
        const key = argv[index];
        if (!key.startsWith("--")) continue;
        args[key.slice(2)] = argv[index + 1];
        index += 1;
    }
    return args;
}

function expandCocosUuid(value) {
    if (value.length !== 22) return value;

    const alphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/";
    const hex = "0123456789abcdef";
    let result = value.slice(0, 2);

    for (let index = 2; index < value.length; index += 2) {
        const left = alphabet.indexOf(value[index]);
        const right = alphabet.indexOf(value[index + 1]);
        if (left < 0 || right < 0) {
            throw new Error(`无法展开 Cocos UUID: ${value}`);
        }
        result += hex[left >> 2];
        result += hex[((left & 3) << 2) | (right >> 4)];
        result += hex[right & 15];
    }

    return [
        result.slice(0, 8),
        result.slice(8, 12),
        result.slice(12, 16),
        result.slice(16, 20),
        result.slice(20),
    ].join("-");
}

function decodeXorText(value) {
    const trimmed = value.trimStart();
    if (trimmed.startsWith("{") || trimmed.startsWith("[") || trimmed.startsWith("package ")) {
        return value;
    }
    const bytes = Buffer.from(value, "utf8");
    for (let index = 0; index < bytes.length; index += 1) {
        bytes[index] ^= 1;
    }
    const decoded = bytes.toString("utf8");
    return decoded.startsWith("03254") ? decoded.slice(5) : decoded;
}

function extractTextAsset(raw, assetName) {
    const document = JSON.parse(raw);
    const value = document?.[5]?.[0]?.[2];
    if (typeof value !== "string") {
        throw new Error(`${assetName} 不是可识别的 Cocos TextAsset`);
    }
    return decodeXorText(value);
}

async function fetchText(url, attempts = 3) {
    let lastError;
    for (let attempt = 1; attempt <= attempts; attempt += 1) {
        try {
            const response = await fetch(url);
            if (!response.ok) {
                throw new Error(`${response.status} ${response.statusText}`);
            }
            return await response.text();
        } catch (error) {
            lastError = error;
        }
    }
    throw new Error(`下载失败 ${url}: ${lastError?.message || lastError}`);
}

async function mapConcurrent(items, concurrency, worker) {
    const results = new Array(items.length);
    let nextIndex = 0;

    async function run() {
        while (nextIndex < items.length) {
            const index = nextIndex;
            nextIndex += 1;
            results[index] = await worker(items[index], index);
        }
    }

    await Promise.all(
        Array.from({ length: Math.min(concurrency, items.length) }, () => run()),
    );
    return results;
}

function parseProtocolSource(source) {
    const startMatch = /^Protocol: \[ function\([^\n]+/m.exec(source);
    if (!startMatch) {
        throw new Error("客户端脚本中没有找到 Protocol 模块");
    }

    const remainder = source.slice(startMatch.index + startMatch[0].length);
    const nextModule = /^([A-Za-z0-9_$]+): \[ function\([^\n]+/m.exec(remainder);
    const block = nextModule ? remainder.slice(0, nextModule.index) : remainder;
    const entries = [];
    const expression = /t\.([A-Za-z_$][A-Za-z0-9_$]*)\s*=\s*([0-9]+(?:e[0-9]+)?);/g;
    let match;

    while ((match = expression.exec(block)) !== null) {
        entries.push([match[1], Number(match[2])]);
    }

    if (entries.length < 1000) {
        throw new Error(`只解析到 ${entries.length} 个协议，拒绝覆盖现有协议文件`);
    }

    return entries;
}

function renderProtocol(entries) {
    const lines = [
        "// Generated by scripts/sync-apk-protocols.mjs. Do not edit by hand.",
        "class Protocol {",
        "    static getProtocalIdRemainder(id) {",
        "        return id >= 100000 ? id % 100000 : id % 10000;",
        "    }",
        "",
    ];

    for (const [name, value] of entries) {
        lines.push(`    static ${name} = ${value};`);
    }

    lines.push("}", "", "export default Protocol;", "");
    return lines.join("\n");
}

function normalizeGeneratedText(value) {
    return value
        .replace(/\r\n/g, "\n")
        .split("\n")
        .map(line => line.trimEnd())
        .join("\n");
}

function qualifyMethod(method) {
    if (!method) return undefined;
    return method.includes(".") ? method : `CityMsg.${method}`;
}

function protocolRemainder(id) {
    return id >= 100000 ? id % 100000 : id % 10000;
}

function mergeMessageInfoAssets(assets) {
    const merged = {};
    const seen = new Set();

    for (const asset of assets) {
        let msgInfo;
        try {
            msgInfo = JSON.parse(asset.text);
        } catch (error) {
            throw new Error(`${asset.assetPath} 解密后不是有效 JSON: ${error.message}`);
        }
        for (const [protoName, messages] of Object.entries(msgInfo)) {
            if (!Array.isArray(messages)) {
                throw new Error(`${asset.assetPath} 的 ${protoName} 不是消息数组`);
            }
            merged[protoName] ||= [];
            for (const message of messages) {
                const identity = [
                    protoName,
                    message.key || "",
                    message.cmMethod || "",
                    message.smMethod || "",
                    message.fSmMethod || "",
                    message.byteDecode || "",
                ].join("\u0000");
                if (seen.has(identity)) continue;
                seen.add(identity);
                merged[protoName].push(message);
            }
        }
    }

    return merged;
}

function buildMessageIndexes(cityMsgInfo, protocolEntries) {
    const protocolMap = new Map(protocolEntries);
    const cmdList = {};
    const resvCmdList = {};
    const reqData = {};
    const rspData = {};
    const missingKeys = [];
    const collisions = [];
    let byteDecodeIndex = 0;

    for (const [protoName, messages] of Object.entries(cityMsgInfo)) {
        for (const message of messages) {
            if (message.byteDecode) {
                cmdList[byteDecodeIndex] = {
                    comment: message.comment || "",
                    smMsgId: byteDecodeIndex,
                    byteDecode: qualifyMethod(message.byteDecode),
                };
                byteDecodeIndex += 1;
            }

            if (!message.key) continue;
            const id = protocolMap.get(message.key);
            if (id === undefined) {
                missingKeys.push(message.key);
                continue;
            }

            const smMsgId = protocolRemainder(id);
            const cmMethod = qualifyMethod(message.cmMethod);
            const smMethod = qualifyMethod(message.smMethod);
            const fSmMethod = qualifyMethod(message.fSmMethod);
            const command = {
                comment: message.comment || "",
                smMsgId,
            };

            if (cmMethod) command.cmMethod = cmMethod;
            if (smMethod) command.smMethod = smMethod;
            if (fSmMethod) command.fSmMethod = fSmMethod;
            if (message.byteDecode) command.byteDecode = qualifyMethod(message.byteDecode);
            cmdList[id] = command;

            reqData[id] = {
                name: protoName,
                comments: message.comment || "",
                protocol: message.key,
                method: cmMethod || "",
            };

            if (smMethod) {
                const existing = resvCmdList[smMsgId];
                if (existing?.smMethod && existing.smMethod !== smMethod) {
                    const candidates = existing.candidates
                        ? [...existing.candidates]
                        : [{
                            smMethod: existing.smMethod,
                            ...(existing.fSmMethod ? { fSmMethod: existing.fSmMethod } : {}),
                        }];
                    if (!candidates.some(candidate => candidate.smMethod === smMethod)) {
                        candidates.push({
                            smMethod,
                            ...(fSmMethod ? { fSmMethod } : {}),
                        });
                        collisions.push(`${smMsgId}: ${existing.smMethod} / ${smMethod}`);
                    }
                    resvCmdList[smMsgId] = { ...existing, candidates };
                } else {
                    resvCmdList[smMsgId] = {
                        smMethod,
                        ...(fSmMethod ? { fSmMethod } : {}),
                    };
                }
                const responseMetadata = {
                    name: protoName,
                    comments: message.comment || "",
                    protocol: message.key,
                    method: smMethod,
                };
                if (!rspData[smMsgId]) {
                    rspData[smMsgId] = responseMetadata;
                } else if (rspData[smMsgId].method !== smMethod) {
                    rspData[smMsgId].candidates ||= [{ ...rspData[smMsgId] }];
                    if (!rspData[smMsgId].candidates.some(candidate => candidate.method === smMethod)) {
                        rspData[smMsgId].candidates.push(responseMetadata);
                    }
                }
            }
        }
    }

    if (missingKeys.length > 0) {
        throw new Error(`CityMsgInfo 中有 ${missingKeys.length} 个未知协议: ${missingKeys.slice(0, 10).join(", ")}`);
    }
    return { cmdList, resvCmdList, reqData, rspData, collisions };
}

function classifyProtocolRisk(name, comment = "") {
    const value = `${name} ${comment}`.toUpperCase();
    if (/(RECHARGE|PAY|PURCHASE|BUY|BID|AUCTION|TRADE|SELL)/.test(value)) return "purchase";
    if (/(FIGHT|BATTLE|CHALLENGE|MATCH|ATTACK|ROB|PVP|WAR)/.test(value)) return "combat";
    if (/(REWARD|CLAIM|SIGN|FREE|GIFT)/.test(value)) return "claim";
    return "observe";
}

function buildActivityRegistry(msgInfoAssets, protocolEntries) {
    const protocolMap = new Map(protocolEntries);
    const groups = new Map();

    for (const asset of msgInfoAssets) {
        const source = path.basename(asset.assetPath);
        const msgInfo = JSON.parse(asset.text);
        for (const [protobuf, messages] of Object.entries(msgInfo)) {
            if (!groups.has(protobuf)) {
                groups.set(protobuf, {
                    name: protobuf,
                    sources: [],
                    remote: false,
                    enabled: true,
                    protocols: [],
                });
            }
            const group = groups.get(protobuf);
            if (!group.sources.includes(source)) group.sources.push(source);
            if (source !== "CityMsgInfo") group.remote = true;

            for (const message of messages) {
                if (!message.key) continue;
                const id = protocolMap.get(message.key);
                const item = {
                    key: message.key,
                    id,
                    responseId: id === undefined ? undefined : protocolRemainder(id),
                    comment: message.comment || "",
                    requestMethod: qualifyMethod(message.cmMethod) || "",
                    responseMethod: qualifyMethod(message.smMethod) || "",
                    risk: classifyProtocolRisk(message.key, message.comment),
                };
                if (!group.protocols.some(protocol =>
                    protocol.key === item.key &&
                    protocol.requestMethod === item.requestMethod &&
                    protocol.responseMethod === item.responseMethod
                )) {
                    group.protocols.push(item);
                }
            }
        }
    }

    return [...groups.values()].sort((left, right) => left.name.localeCompare(right.name));
}

async function writeJson(filePath, value) {
    await fs.writeFile(filePath, `${JSON.stringify(value, null, 4)}\n`, "utf8");
}

async function main() {
    const args = parseArgs(process.argv.slice(2));
    if (!args.manifest || !args["client-script"]) {
        throw new Error(
            "用法: node scripts/sync-apk-protocols.mjs --manifest <project.manifest> --client-script <decrypted-index.js>",
        );
    }

    const manifestPath = path.resolve(args.manifest);
    const clientScriptPath = path.resolve(args["client-script"]);
    const manifest = JSON.parse(await fs.readFile(manifestPath, "utf8"));
    const packageUrl = String(manifest.packageUrl || "").replace(/\/$/, "");
    if (!packageUrl.startsWith("https://")) {
        throw new Error(`manifest packageUrl 无效: ${packageUrl}`);
    }

    const clientSource = await fs.readFile(clientScriptPath, "utf8");
    const protocolEntries = parseProtocolSource(clientSource);
    const resourceConfig = JSON.parse(
        await fetchText(`${packageUrl}/assets/resources/config.json`),
    );
    const pathEntries = Object.entries(resourceConfig.paths);
    const selected = pathEntries.filter(([, value]) => {
        const assetPath = value?.[0];
        return assetPath?.startsWith("protobuf/") || /^json\/.+MsgInfo$/.test(assetPath);
    });

    const temporaryRoot = await fs.mkdtemp(path.join(os.tmpdir(), "xddq-protocols-"));
    try {
        const assets = await mapConcurrent(selected, 12, async ([uuidIndex, value]) => {
            const assetPath = value[0];
            const uuid = expandCocosUuid(resourceConfig.uuids[Number(uuidIndex)]);
            const url = `${packageUrl}/assets/resources/import/${uuid.slice(0, 2)}/${uuid}.json`;
            const raw = await fetchText(url);
            const text = extractTextAsset(raw, assetPath);
            return { assetPath, text };
        });

        const msgInfoAssets = assets.filter(asset => /^json\/.+MsgInfo$/.test(asset.assetPath));
        if (!msgInfoAssets.some(asset => asset.assetPath === "json/CityMsgInfo")) {
            throw new Error("资源配置中没有 CityMsgInfo");
        }
        const mergedMsgInfo = mergeMessageInfoAssets(msgInfoAssets);
        const indexes = buildMessageIndexes(mergedMsgInfo, protocolEntries);
        const activityRegistry = buildActivityRegistry(msgInfoAssets, protocolEntries);
        const protobufAssets = assets.filter(asset => asset.assetPath.startsWith("protobuf/"));

        for (const asset of protobufAssets) {
            if (!asset.text.trimStart().startsWith("package ")) {
                throw new Error(`${asset.assetPath} 解密后不是 protobuf 文本`);
            }
            const name = asset.assetPath.slice("protobuf/".length);
            await fs.writeFile(path.join(temporaryRoot, name), normalizeGeneratedText(asset.text), "utf8");
        }

        await fs.mkdir(protobufOutput, { recursive: true });
        await fs.mkdir(jsonOutput, { recursive: true });

        const wantedFiles = new Set(protobufAssets.map(asset => asset.assetPath.slice(9)));
        for (const existing of await fs.readdir(protobufOutput)) {
            if (!wantedFiles.has(existing)) {
                await fs.unlink(path.join(protobufOutput, existing));
            }
        }
        for (const fileName of wantedFiles) {
            await fs.copyFile(
                path.join(temporaryRoot, fileName),
                path.join(protobufOutput, fileName),
            );
        }

        await fs.writeFile(protocolOutput, renderProtocol(protocolEntries), "utf8");
        await writeJson(path.join(jsonOutput, "CityMsgInfo"), mergedMsgInfo);
        await writeJson(path.join(jsonOutput, "cmdList.json"), indexes.cmdList);
        await writeJson(path.join(jsonOutput, "resvCmdList.json"), indexes.resvCmdList);
        await writeJson(path.join(jsonOutput, "activityRegistry.json"), activityRegistry);
        await writeJson(path.join(grpcRoot, "req_data.json"), indexes.reqData);
        await writeJson(path.join(grpcRoot, "rsp_data.json"), indexes.rspData);
        await writeJson(path.join(grpcRoot, "version.json"), {
            version: manifest.version,
            buildID: manifest.buildID,
            packageID: manifest.packageID,
            packageUrl,
            protocolCount: protocolEntries.length,
            protobufCount: protobufAssets.length,
            msgInfoAssetCount: msgInfoAssets.length,
            mappedRequestCount: Object.keys(indexes.reqData).length,
            mappedResponseCount: Object.keys(indexes.rspData).length,
            responseCollisionCount: indexes.collisions.length,
            activityGroupCount: activityRegistry.length,
        });

        console.log(
            `已同步 ${protocolEntries.length} 个协议、${protobufAssets.length} 个 protobuf、${msgInfoAssets.length} 份消息映射（${manifest.version}.${manifest.buildID}）`,
        );
    } finally {
        await fs.rm(temporaryRoot, { recursive: true, force: true });
    }
}

export { buildMessageIndexes };

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
    main().catch(error => {
        console.error(error.stack || error.message || error);
        process.exitCode = 1;
    });
}
